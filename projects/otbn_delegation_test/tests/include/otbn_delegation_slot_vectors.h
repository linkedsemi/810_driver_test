/*
 * Fixed vectors shared by the slot-signing case's server main and the shared
 * test body.
 *
 * All private scalars are little-endian, the format
 * ls_otbn_ecdsa_key_slot_register() expects (the same layout
 * mbedtls_mpi_write_binary_le() produces). Public keys are the usual
 * big-endian hex strings read by mbedtls_ecp_point_read_string().
 *
 * Slot map used by case_slot:
 *   0 = P256 key A
 *   1 = P384
 *   2 = SM2
 *   3 = P256 key B (same curve as slot 0, different key)
 *   4 = scratch (server registration/race tests only; never used by the client)
 *   7 = permanently empty (client's "unregistered slot" probe)
 *   8 = first out-of-range id on the server (COUNT is 8 there); the client's
 *       out-of-range probe uses 0xFFFFFFFF and does not depend on COUNT
 */

